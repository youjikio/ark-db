// 既定文（方法 × 危険度）
function def(c) {
  const big = c.danger === "高" || c.danger === "最高";
  const mid = c.danger === "中";
  const water = (c.tags || []).indexOf("水中") >= 0;
  const air = (c.tags || []).indexOf("空") >= 0;
  switch (c.tame) {
    case "気絶":
      if (water) return "**クロスボウ＋麻酔矢**（水中では弓より有効）／スキューバ装備かディプロカウルス（酸素）／" +
        (c.food || "餌") + "／麻酔薬／逃げ足のある水棲の足（イルカ・バリオニクス）";
      if (air) return "ボーラ（低空に落とす）＋こん棒、または弓＋**麻酔矢**／" + (c.food || "餌") +
        "／麻酔薬／落下地点を見失わないよう開けた場所で";
      if (big) return "弓かライフル＋**麻酔矢**（多め）／石の囲いなどのトラップ／" + (c.food || "餌") + "／麻酔薬・ナルコベリー／回復薬";
      if (mid) return "ボーラ＋こん棒、または弓＋麻酔矢／" + (c.food || "餌") + "／麻酔薬（ナルコベリー＋腐肉を臼で）";
      return "ボーラ＋こん棒（またはパチンコ）／" + (c.food || "餌") + "／念のため麻酔薬";
    case "手渡し":
      return (c.food || "餌") + "を手に持つ／周囲の敵を先に片付ける／逃げられた時のために足の速い恐竜";
    case "卵":
      return "卵を盗む足／孵化用のたき火かエアコン／育成用の餌と餌箱";
    case "特殊":
      return "専用の手順（下のコツを参照）／" + (c.food && c.food !== "—" ? c.food : "必要な素材を先に用意");
    case "不可":
      return "テイム不可。倒すための装備と恐竜";
    default:
      return "テイム方法が未確定。公式Wikiで確認してから準備を";
  }
}

// 有料DLC由来の生き物への追記
const DLC_NOTE = "※**そのDLCを買っている人だけ**が使えます（サーバーに出ても未購入者はテイム不可）。";

let n = 0;
doc.creatures.forEach(c => {
  let p = OVERRIDE[c.id] || def(c);
  if ((c.tags || []).indexOf("有料DLC") >= 0) p += "／" + DLC_NOTE;
  c.prep = p; n++;
});

